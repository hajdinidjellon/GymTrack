/**
 * Okilo's AlarmKit module, at prebuild:
 * - the permission text iOS shows before the first alarm;
 * - a Swift file in the app target that lists the module's App Intents:
 *   without it the "Ouvrir Okilo" button of the alarm does nothing.
 */
const { IOSConfig, withDangerousMod, withInfoPlist, withXcodeProject } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const FILE = 'OkiloAlarmIntents.swift';
const SOURCE = `// Generated by modules/okilo-alarm/app.plugin.js
#if canImport(AlarmKit) && canImport(AppIntents)
import AppIntents
// internal like Expo's generated ExpoModulesProvider: a plain import there fails (Swift 6)
internal import OkiloAlarm

@available(iOS 26.0, *)
struct OkiloAppIntentsPackage: AppIntentsPackage {
  static var includedPackages: [any AppIntentsPackage.Type] {
    [OkiloAlarmIntents.self]
  }
}
#endif
`;

function withUsageText(config, { usage }) {
  return withInfoPlist(config, (mod) => {
    mod.modResults.NSAlarmKitUsageDescription = usage;
    return mod;
  });
}

function withIntentsFile(config) {
  config = withDangerousMod(config, [
    'ios',
    (mod) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
      const dir = path.join(mod.modRequest.platformProjectRoot, projectName);
      fs.writeFileSync(path.join(dir, FILE), SOURCE);
      return mod;
    },
  ]);
  return withXcodeProject(config, (mod) => {
    const project = mod.modResults;
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
    const filepath = `${projectName}/${FILE}`;
    if (project.hasFile(filepath)) return mod;
    // The app, not the widget extension expo-widgets adds next to it
    const [targetUuid] =
      IOSConfig.Target.getNativeTargets(project).find(([, target]) =>
        IOSConfig.Target.isTargetOfType(target, IOSConfig.Target.TargetType.APPLICATION),
      ) ?? [];
    IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project, targetUuid });
    return mod;
  });
}

module.exports = function withOkiloAlarm(config, props = {}) {
  const usage = props.usage ?? 'Okilo sonne la fin de ton repos comme un minuteur, même quand tu es sur une autre app.';
  return withIntentsFile(withUsageText(config, { usage }));
};
